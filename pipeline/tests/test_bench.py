"""The bench's own plumbing: by-chance bars are put back, tallies count partly as half, and the pull-request report
shows exactly the sentences that changed."""
from pipeline.bench import calls, report
from pipeline.export import previews


def test_opened_bars_are_restored():
    before = (previews.EDGE_GAP, previews.BOTH, previews.DUEL_BAR)
    with calls.opened(EDGE_GAP=0, BOTH=0, DUEL_BAR=0):
        assert (previews.EDGE_GAP, previews.BOTH, previews.DUEL_BAR) == (0, 0, 0)
    assert (previews.EDGE_GAP, previews.BOTH, previews.DUEL_BAR) == before
    try:
        with calls.opened(EDGE_GAP=0):
            raise RuntimeError
    except RuntimeError:
        pass
    assert previews.EDGE_GAP == before[0]


def test_tally_counts_partly_as_half_and_keeps_na_out():
    t = calls.Tally()
    c = {"kind": "pace", "metric": "pace", "check": {"direction": "above"}}
    for v in ("held", "partly", "missed", "na", None):
        t.add(2025, c, v)
    out = t.out()["pace"]
    assert set(out) == {"all", "fast"}
    a = out["all"]["all"]
    assert (a["calls"], a["graded"], a["na"]) == (5, 3, 2)
    assert a["rate"] == 0.5
    assert out["fast"]["2025"]["rate"] == 0.5


def _samples(*sentences):
    return {"games": {"1": {"game": "CAR at VAN", "date": "2026-10-20", "pages": {"post-game": [["story.paras[0]", s] for s in sentences]}}}}


def test_samples_compare_shows_only_changed_sentences():
    base = _samples("The Hurricanes won.", "Kochetkov made 14 saves.", "Same as before.")
    head = _samples("The Hurricanes won 6-3.", "Kochetkov made 14 saves.", "Same as before.")
    out, n = report.samples_compare(base, head)
    assert n == 1
    text = "\n".join(out)
    assert "- The Hurricanes won." in text and "+ The Hurricanes won 6-3." in text
    assert "Kochetkov" not in text and "Same as before" not in text
    assert report.samples_compare(base, base) == ([], 0)


def test_calls_compare_lists_moved_kinds_only():
    rate = lambda graded, held: {"graded": graded, "held": held, "partly": 0, "missed": graded - held, "na": 0, "calls": graded,
                                 "rate": held / graded}
    run = lambda held: {"published": {"edge": {"all": {"all": rate(100, held)}}, "pace": {"all": {"all": rate(10, 5)}}},
                        "chance": {"edge": {"all": {"all": rate(1000, 550)}}}}
    out = "\n".join(report.calls_compare(run(60), run(64)))
    assert "60% → 64%" in out and "55%" in out
    assert "Pace" not in out
    assert report.calls_compare(run(60), run(60)) == ["No call's replayed record changed."]


def test_pr_comment_carries_the_footer_and_stays_short():
    body = report.pr_comment(None, None, _samples("a b c d"), _samples("a b c e"))
    assert body.rstrip().endswith("_Generated by [Claude Code](https://claude.ai/code)_")
    assert len(body) < report.MAX_CHARS + 500
